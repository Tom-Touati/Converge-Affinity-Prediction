"""Error-analysis and data-description figures.

Every figure is regenerated by one command and written to ``reports/figures/``. Nothing is
hand-drawn and no number in a caption is typed by hand.

    python -m src.analysis labels
"""
from __future__ import annotations

import argparse

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from . import evaluate, paths, splits  # noqa: E402

# Diverging encoding: ddG is signed around a physically meaningful zero, so the two poles are
# warm/cool with a neutral gray midpoint. Never a sequential ramp for a signed quantity.
STAB = "#2a78d6"      # cool pole: stabilising, tighter binding
NEUTRAL = "#c3c2b7"   # neutral midpoint: no meaningful change
DESTAB = "#e34948"    # warm pole: destabilising, weaker binding
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
INK_MUTED = "#898781"
GRID = "#e1e0d9"

FIGDIR = paths.REPORTS / "figures"


def _style(ax):
    ax.set_facecolor(SURFACE)
    ax.grid(axis="y", color=GRID, linewidth=0.8, zorder=0)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)


def plot_labels(bin_width: float = 0.25) -> "str":
    """Distribution of ddG, with each 'destabilising' criterion drawn on the same axis.

    The three criteria do not agree, which is the whole point of the figure: the headline
    imbalance depends entirely on which one is quoted.
    """
    d = splits.load()
    y = d["ddG"].to_numpy(float)
    lo, hi = evaluate.CLASS_EDGES

    fig = plt.figure(figsize=(10.5, 7.6), facecolor=SURFACE)
    gs = fig.add_gridspec(2, 1, height_ratios=[2.6, 1.0], hspace=0.42)

    # ---- panel 1: the histogram ------------------------------------------------------------
    ax = fig.add_subplot(gs[0])
    _style(ax)
    edges = np.arange(np.floor(y.min() * 4) / 4, np.ceil(y.max() * 4) / 4 + bin_width, bin_width)
    counts, edges = np.histogram(y, bins=edges)
    centers = (edges[:-1] + edges[1:]) / 2
    colors = [STAB if c < lo else (DESTAB if c > hi else NEUTRAL) for c in centers]
    # 2px-equivalent surface gap between adjacent fills
    ax.bar(centers, counts, width=bin_width * 0.88, color=colors, zorder=3, linewidth=0)

    for x in (lo, hi):
        ax.axvline(x, color=INK_MUTED, linewidth=1.0, linestyle=(0, (4, 3)), zorder=4)
    ax.axvline(0, color=INK, linewidth=1.4, zorder=5)

    ax.annotate("0  no change", xy=(0, ax.get_ylim()[1] * 0.97), xytext=(3, 0),
                textcoords="offset points", fontsize=9, color=INK, va="top")
    ax.annotate(f"class edges  {lo:+.1f} / {hi:+.1f}", xy=(hi, ax.get_ylim()[1] * 0.80),
                xytext=(6, 0), textcoords="offset points", fontsize=9, color=INK_2, va="top")

    # the |ddG| > 1 band used by the sign-accuracy metric
    ymax = ax.get_ylim()[1]
    ax.annotate("", xy=(1.0, ymax * 0.60), xytext=(y.max(), ymax * 0.60),
                arrowprops=dict(arrowstyle="<->", color=INK_MUTED, linewidth=1.0))
    ax.annotate("", xy=(-1.0, ymax * 0.60), xytext=(y.min(), ymax * 0.60),
                arrowprops=dict(arrowstyle="<->", color=INK_MUTED, linewidth=1.0))
    ax.text(3.6, ymax * 0.635, "|ddG| > 1: the sign-accuracy subset", fontsize=9,
            color=INK_2, ha="center")

    mean, med = y.mean(), np.median(y)
    ax.set_xlabel("ddG  (kcal/mol)   -- positive means weaker binding", fontsize=10, color=INK_2)
    ax.set_ylabel("mutations", fontsize=10, color=INK_2)
    ax.set_title(
        f"ddG is skewed towards weaker binding   (n = {len(y)},  mean {mean:+.2f},  "
        f"median {med:+.2f},  sd {y.std():.2f})",
        fontsize=12.5, color=INK, loc="left", pad=14,
    )
    handles = [
        plt.Rectangle((0, 0), 1, 1, color=STAB),
        plt.Rectangle((0, 0), 1, 1, color=NEUTRAL),
        plt.Rectangle((0, 0), 1, 1, color=DESTAB),
    ]
    ax.legend(handles, [f"stabilising  (< {lo:+.1f})", f"neutral  ({lo:+.1f} to {hi:+.1f})",
                        f"destabilising  (> {hi:+.1f})"],
              frameon=False, fontsize=9.5, labelcolor=INK_2, loc="upper right",
              bbox_to_anchor=(1.0, 0.94))

    # ---- panel 2: the same rows, split three ways -------------------------------------------
    ax2 = fig.add_subplot(gs[1])
    ax2.set_facecolor(SURFACE)
    for s in ("top", "right", "left", "bottom"):
        ax2.spines[s].set_visible(False)
    ax2.tick_params(colors=INK_2, labelsize=9.5, length=0)
    ax2.set_xlim(0, 100)
    ax2.set_xticks([0, 25, 50, 75, 100])
    ax2.set_xticklabels(["0%", "25%", "50%", "75%", "100%"])

    big = np.abs(y) > 1
    rows = [
        ("sign of ddG\n(all 997)", (y < 0).mean(), (y == 0).mean(), (y > 0).mean(), len(y)),
        (f"class edges {lo:+.1f}/{hi:+.1f}\n(all 997)",
         (y < lo).mean(), ((y >= lo) & (y <= hi)).mean(), (y > hi).mean(), len(y)),
        ("|ddG| > 1 only\n(490 rows)",
         (y[big] < 0).mean(), 0.0, (y[big] > 0).mean(), int(big.sum())),
    ]
    labels = []
    for i, (name, a, b, c, n) in enumerate(rows):
        labels.append(name)
        left = 0.0
        for frac, col in ((a, STAB), (b, NEUTRAL), (c, DESTAB)):
            if frac <= 0:
                continue
            ax2.barh(i, frac * 100, left=left * 100, color=col, height=0.55,
                     zorder=3, linewidth=1.4, edgecolor=SURFACE)
            if frac > 0.045:
                ax2.text(left * 100 + frac * 50, i, f"{frac * 100:.1f}%", ha="center",
                         va="center", fontsize=9.5, color="#ffffff" if col != NEUTRAL else INK,
                         zorder=4)
            left += frac
    ax2.set_yticks(range(len(rows)))
    ax2.set_yticklabels(labels)
    ax2.invert_yaxis()
    ax2.set_title("The same data, under each criterion for \"destabilising\"",
                  fontsize=11.5, color=INK, loc="left", pad=10)

    FIGDIR.mkdir(parents=True, exist_ok=True)
    out = FIGDIR / "ddG_distribution.png"
    fig.savefig(out, dpi=170, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)

    print(f"n={len(y)}  mean {mean:+.3f}  median {med:+.3f}  sd {y.std():.3f}")
    print(f"sign:        stab {(y < 0).mean():.1%}  zero {(y == 0).mean():.1%}  "
          f"destab {(y > 0).mean():.1%}")
    print(f"class edges: stab {(y < lo).mean():.1%}  neutral {((y >= lo) & (y <= hi)).mean():.1%}  "
          f"destab {(y > hi).mean():.1%}")
    print(f"|ddG|>1:     n={big.sum()}  destab {(y[big] > 0).mean():.1%}")
    print(f"wrote {out.relative_to(paths.ROOT)}")
    return str(out)


FIGURES = {"labels": plot_labels}


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("figure", nargs="?", default="labels", choices=sorted(FIGURES))
    a = p.parse_args()
    FIGURES[a.figure]()


if __name__ == "__main__":
    main()
