"""Regenerate ``results/summary.md`` from ``results/results.csv``. Rule 4.

Aggregates twice, because under grouped CV the two disagree and the disagreement matters:

* **over folds, within a seed, then over seeds** -- the mean ± std the plan asks for.
* **pooled over all out-of-fold rows** -- reported alongside, because a fold mean hides that
  the folds differ in label distribution.

Also writes the "vs. paper" section from ``results/benchmarks.csv`` when it exists, putting
ProtAttBA's published ESM2 numbers next to ours.

Run: ``python scripts/summarize.py``
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.fusion import results as R  # noqa: E402

SUMMARY = R.RESULTS_DIR / "summary.md"

#: ProtAttBA, Bioinformatics 2025, Table 1, ESM2 column. Reproduced from their own shipped
#: predictions in experiments/protattba_repro/verify_published.py.
PUBLISHED = {
    "S1131": {"pearson": (0.84, 0.05), "spearman": (0.75, 0.06), "rmse": (1.31, 0.09)},
    "AB645": {"pearson": (0.66, 0.10), "spearman": (0.62, 0.10), "rmse": (1.40, 0.16)},
    "AB1101": {"pearson": (0.63, 0.05), "spearman": (0.59, 0.05), "rmse": (1.62, 0.09)},
}

METRICS = ["pearson", "spearman", "rmse", "acc3", "f1_macro3", "per_complex_spearman"]


def _agg(df: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    """Mean over folds per seed, then mean ± std over seeds."""
    num = [m for m in METRICS if m in df.columns]
    df = df.copy()
    for c in num:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    per_seed = df.groupby(by + ["seed"], dropna=False)[num].mean().reset_index()
    out = per_seed.groupby(by, dropna=False)[num].agg(["mean", "std"])
    counts = df.groupby(by, dropna=False).agg(folds=("fold", "nunique"),
                                              seeds=("seed", "nunique"))
    # counts has single-level columns and out has two; lift counts so the join is legal.
    counts.columns = pd.MultiIndex.from_product([counts.columns, [""]])
    joined = out.join(counts)
    joined[("folds", "")] = joined[("folds", "")].astype(int)
    joined[("seeds", "")] = joined[("seeds", "")].astype(int)
    return joined


def _fmt(mean, std, places=3) -> str:
    if pd.isna(mean):
        return "n/a"
    if pd.isna(std):
        return f"{mean:.{places}f}"
    return f"{mean:.{places}f} ± {std:.{places}f}"


def table(df: pd.DataFrame, by: list[str]) -> str:
    agg = _agg(df, by)
    have = [m for m in METRICS if (m, "mean") in agg.columns]
    head = "| " + " | ".join(by + ["folds", "seeds"] + have) + " |"
    rule = "|" + "|".join(["---"] * (len(by) + 2 + len(have))) + "|"
    lines = [head, rule]
    order = agg[("pearson", "mean")].sort_values(ascending=False).index \
        if ("pearson", "mean") in agg.columns else agg.index
    for key in order:
        keys = list(key) if isinstance(key, tuple) else [key]
        cells = [str(k) for k in keys]
        cells += [str(int(agg.loc[key, ("folds", "")])), str(int(agg.loc[key, ("seeds", "")]))]
        for m in have:
            cells.append(_fmt(agg.loc[key, (m, "mean")], agg.loc[key, (m, "std")]))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def vs_paper(bench: pd.DataFrame) -> str:
    out = ["", "## vs. ProtAttBA Table 1 (ESM2 column)", "",
           "Their protocol: 10-fold CV on S1131 and AB645, 5-fold on AB1101, per-fold mean and",
           "population standard deviation. Published figures were verified against the",
           "predictions their repo ships (`experiments/protattba_repro/verify_published.py`).",
           ""]
    for ds in ("S1131", "AB645", "AB1101"):
        sub = bench[bench["dataset"] == ds]
        pub = PUBLISHED[ds]
        out += [f"### {ds}", "",
                "| model | PCC | Spearman | RMSE |", "|---|---|---|---|",
                f"| ProtAttBA (published) | {pub['pearson'][0]:.2f} ± {pub['pearson'][1]:.2f} "
                f"| {pub['spearman'][0]:.2f} ± {pub['spearman'][1]:.2f} "
                f"| {pub['rmse'][0]:.2f} ± {pub['rmse'][1]:.2f} |"]
        if sub.empty:
            out += ["| *(ours: not run)* | | | |"]
        else:
            agg = _agg(sub, ["exp"])
            for exp in agg.index:
                out.append("| " + " | ".join([
                    str(exp),
                    _fmt(agg.loc[exp, ("pearson", "mean")], agg.loc[exp, ("pearson", "std")], 3),
                    _fmt(agg.loc[exp, ("spearman", "mean")], agg.loc[exp, ("spearman", "std")], 3),
                    _fmt(agg.loc[exp, ("rmse", "mean")], agg.loc[exp, ("rmse", "std")], 3),
                ]) + " |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    df = R.load_results()
    parts = ["# Results summary", "",
             "Regenerated by `python scripts/summarize.py`. Mean ± std is over folds within a",
             "seed, then over seeds.", ""]

    if df.empty:
        parts.append("*No results yet.*")
    else:
        parts += [
            "## SKEMPI antibody-antigen, frozen 5-fold by complex", "",
            "Split: `data/splits/skempi_abag_5fold_by_complex.json`, 940 rows, 53 complexes,",
            "seed 0, grouped by PDB id. **This is grouped by complex, not by homology cluster,**",
            "so it is looser than the project's frozen `data/folds.csv` and these numbers are",
            "not comparable to the project's headline figures. `per_complex_spearman` is the",
            "project's headline metric computed on this split, for orientation only.", "",
            table(df[df["dataset"] == "skempi_abag"] if "dataset" in df else df, ["exp"]), "",
        ]

    bench_path = R.BENCHMARKS_CSV
    if bench_path.exists():
        parts.append(vs_paper(pd.read_csv(bench_path)))
    else:
        parts += ["## vs. ProtAttBA Table 1", "",
                  "*`results/benchmarks.csv` not written yet (E6b).*", ""]

    if R.FAILURES_MD.exists():
        parts += ["## Failures", "",
                  f"See `{R.FAILURES_MD.relative_to(R.RESULTS_DIR.parent)}`.", ""]

    SUMMARY.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY.write_text("\n".join(parts))
    print(f"wrote {SUMMARY}")
    print("\n".join(parts[:40]))


if __name__ == "__main__":
    main()
